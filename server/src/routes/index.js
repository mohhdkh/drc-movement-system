const express = require('express')
const areaManagerRoutes = require('./areaManagerRoutes')
const adminRoutes = require('./adminRoutes')
const authRoutes = require('./authRoutes')
const employeeRoutes = require('./employeeRoutes')
const driverRoutes = require('./driverRoutes')
const gpsDeviceRoutes = require('./gpsDeviceRoutes')
const healthRoutes = require('./healthRoutes')
const movementRoutes = require('./movementRoutes')
const safetyRoutes = require('./safetyRoutes')
const supplyChainRoutes = require('./supplyChainRoutes')
const vehicleRoutes = require('./vehicleRoutes')
const { listLocations } = require('../controllers/locationController')
const { authenticate } = require('../middleware/authenticate')

const router = express.Router()

router.use('/admin', adminRoutes)
router.use('/auth', authRoutes)
router.use('/area-manager', areaManagerRoutes)
router.use('/health', healthRoutes)
router.use('/employees', employeeRoutes)
router.use('/drivers', driverRoutes)
router.use('/gps-devices', gpsDeviceRoutes)
router.use('/movements', movementRoutes)
router.use('/safety', safetyRoutes)
router.use('/supply-chain', supplyChainRoutes)
router.use('/vehicles', vehicleRoutes)
router.get('/locations', authenticate(), listLocations)

module.exports = router
